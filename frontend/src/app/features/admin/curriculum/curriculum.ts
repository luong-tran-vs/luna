import {
  afterNextRender,
  ChangeDetectionStrategy,
  Component,
  computed,
  inject,
  Injector,
  signal,
  WritableSignal,
} from '@angular/core';
import { ActivatedRoute, Router, RouterLink } from '@angular/router';
import { firstValueFrom, Observable } from 'rxjs';

import { ApiError } from '../../../core/interceptors/error-interceptor';
import {
  CurriculumBoard,
  CurriculumGrammar,
  CurriculumLesson,
  CurriculumSlot,
  CurriculumTopic,
  LessonChecks,
} from '../../../core/models/curriculum';
import { DEFAULT_TARGET_WORDS } from '../../../core/models/generate';
import { Level, LEVELS } from '../../../core/models/lesson';
import { ConfirmDialog } from '../../../shared/components/confirm-dialog/confirm-dialog';
import { SlotImportDialog } from './import-dialog/import-dialog';
import { RemoveDialog } from './remove-dialog/remove-dialog';
import { LevelPicker } from '../../../shared/components/level-picker/level-picker';
import { Loading } from '../../../shared/components/loading/loading';
import { ProgressBar } from '../../../shared/components/progress-bar/progress-bar';
import { AdminApiService } from '../admin-api.service';
import { CurriculumDraft } from './curriculum-draft/curriculum-draft';
import { LessonRow, lessonState, RowState } from './lesson-row/lesson-row';

const LOAD_FAILED = 'Không tải được giáo trình, vui lòng thử lại.';
const APPLY_FAILED = 'Không áp dụng được giáo trình, vui lòng thử lại.';
const GENERATE_FAILED = 'Sinh bài thất bại, vui lòng thử lại.';
const PUBLISH_FAILED = 'Không đăng được bài, vui lòng thử lại.';
const CHECKS_FAILED = 'Không kiểm tra lại được bài, vui lòng thử lại.';
const REMOVE_FAILED = 'Không gỡ được bài, vui lòng thử lại.';
const DRAFT_FAILED = 'AI soạn giáo trình thất bại, vui lòng thử lại.';
const EDIT_FAILED = 'Không mở được bản nháp, vui lòng thử lại.';

export type Filter = 'all' | RowState;

/** What is being generated: one slot, or the empty slots of a topic one after another. */
interface Generation {
  topic: number;
  key: string;
  /** Slots done so far and in all (1 for a single slot). */
  done: number;
  total: number;
}

/** A message shown under a topic's header. */
interface Notice {
  topic: number;
  kind: 'ok' | 'error';
  text: string;
}

/** The lesson the admin asked to take out of the course, waiting for the confirmation. */
interface Removal {
  topic: number;
  lesson: CurriculumLesson;
  title: string;
}

/** A topic as shown with the current filter. */
interface TopicView {
  topic: CurriculumTopic;
  main: CurriculumSlot[];
  extra: CurriculumSlot[];
  others: CurriculumLesson[];
  /** Some row matches the filter. */
  visible: boolean;
  empty: number;
  filled: number;
  hasDraft: boolean;
  missingGrammar: CurriculumGrammar[];
}

/**
 * Giáo trình (admin): the course of the chosen level (?level=, A1 by default), kept in the
 * database. A level without one is drafted by the AI; a draft is edited and approved in
 * CurriculumDraft. An approved course shows one collapsible section per topic with a line per
 * lesson slot (empty, draft or published) and the other lessons of the topic. Empty slots are
 * generated by AI one request at a time; drafts show the rules checked on them and are published
 * from here; any lesson can be taken out of the course ("Gỡ").
 */
@Component({
  selector: 'lu-curriculum',
  imports: [
    RouterLink,
    ConfirmDialog,
    RemoveDialog,
    SlotImportDialog,
    CurriculumDraft,
    LevelPicker,
    Loading,
    ProgressBar,
    LessonRow,
  ],
  templateUrl: './curriculum.html',
  styleUrl: './curriculum.css',
  changeDetection: ChangeDetectionStrategy.OnPush,
})
export class Curriculum {
  private readonly api = inject(AdminApiService);
  private readonly injector = inject(Injector);
  private readonly router = inject(Router);
  private readonly route = inject(ActivatedRoute, { optional: true });

  protected readonly level = signal<Level>(
    levelOf(this.route?.snapshot?.queryParamMap.get('level')),
  );
  protected readonly board = signal<CurriculumBoard | null>(null);
  protected readonly loadError = signal<string | null>(null);
  protected readonly pageError = signal<string | null>(null);
  protected readonly applyOpen = signal(false);
  protected readonly applying = signal(false);
  protected readonly drafting = signal(false);
  protected readonly editing = signal(false);
  protected readonly generation = signal<Generation | null>(null);
  protected readonly publishing = signal<string | null>(null);
  protected readonly rechecking = signal<string | null>(null);
  protected readonly removing = signal<string | null>(null);
  protected readonly removal = signal<Removal | null>(null);
  /** The empty slot a lesson is being imported into (FR-030). */
  protected readonly importing = signal<{ topic: number; slot: CurriculumSlot } | null>(null);
  protected readonly notice = signal<Notice | null>(null);
  protected readonly filter = signal<Filter>('all');
  /** Numbers of the open topics; null until the board is first read. */
  protected readonly expanded = signal<ReadonlySet<number> | null>(null);
  /** Names of the catalogue's topics, suggested when editing a draft. */
  protected readonly topicNames = signal<readonly string[]>([]);

  /** Target words a generated lesson of the level asks for (as the server plans them). */
  protected readonly minWords = computed(() => DEFAULT_TARGET_WORDS[this.level()]);

  protected readonly filters: readonly Filter[] = ['all', 'empty', 'draft', 'published'];

  protected readonly total = computed(() => {
    const b = this.board();
    return b ? b.main + b.extra : 0;
  });
  protected readonly summary = computed(() => {
    const b = this.board();
    if (!b || b.status !== 'approved') {
      return '';
    }
    const empty = this.total() - b.published - b.drafts;
    return `${b.published}/${this.total()} bài đã đăng · ${b.drafts} nháp · ${empty} ô trống`;
  });
  /** Rows of each state on the whole board (slots and other lessons). */
  protected readonly counts = computed(() => {
    const c: Record<RowState, number> = { empty: 0, draft: 0, published: 0 };
    for (const t of this.board()?.topics ?? []) {
      for (const s of t.slots) {
        c[lessonState(s.lesson)]++;
      }
      for (const l of t.others) {
        c[lessonState(l)]++;
      }
    }
    return c;
  });
  protected readonly views = computed<TopicView[]>(() => {
    const f = this.filter();
    const match = (l: CurriculumLesson | null) => f === 'all' || lessonState(l) === f;
    return (this.board()?.topics ?? []).map((t) => {
      const main = t.slots.filter((s) => s.kind === 'main' && match(s.lesson));
      const extra = t.slots.filter((s) => s.kind === 'extra' && match(s.lesson));
      const others = t.others.filter((l) => match(l));
      const empty = t.slots.filter((s) => !s.lesson).length;
      return {
        topic: t,
        main,
        extra,
        others,
        visible: f === 'all' || main.length + extra.length + others.length > 0,
        empty,
        filled: t.slots.length - empty,
        hasDraft: hasDraft(t),
        missingGrammar: t.grammar.filter((g) => !g.published),
      };
    });
  });
  protected readonly busy = computed(
    () =>
      this.generation() !== null ||
      this.applying() ||
      this.removing() !== null ||
      this.drafting() ||
      this.editing(),
  );
  protected readonly applyMessage = computed(
    () =>
      `Tạo các chủ đề còn thiếu, đặt thứ tự các chủ đề ${this.level()} theo giáo trình (chủ đề khác mất vị trí ${this.level()} và xếp sau) và xếp bài trong mỗi lộ trình theo các ô. Bài đã có không bị xoá.`,
  );

  /** The control focused before the remove dialog opened, focused again on cancel. */
  private opener: HTMLElement | null = null;

  constructor() {
    this.load();
    this.api.topics().subscribe({
      next: (topics) => this.topicNames.set(topics.map((t) => t.name)),
      // Only suggestions: the draft can be edited without them.
      error: () => undefined,
    });
  }

  /** Shows another level and keeps it in the address, so a reload stays on it. */
  protected selectLevel(value: string): void {
    const level = levelOf(value);
    if (level === this.level() || this.busy()) {
      return;
    }
    this.level.set(level);
    this.board.set(null);
    this.expanded.set(null);
    this.filter.set('all');
    this.notice.set(null);
    this.pageError.set(null);
    void this.router.navigate([], {
      relativeTo: this.route,
      queryParams: { level },
      queryParamsHandling: 'merge',
      replaceUrl: true,
    });
    this.load();
  }

  protected filterLabel(f: Filter): string {
    const c = this.counts();
    switch (f) {
      case 'all':
        return 'Tất cả';
      case 'empty':
        return `Còn trống (${c.empty})`;
      case 'draft':
        return `Nháp (${c.draft})`;
      case 'published':
        return `Đã đăng (${c.published})`;
    }
  }

  /** Opens the topics having a matching row, or the default ones for "Tất cả". */
  protected selectFilter(f: Filter): void {
    this.filter.set(f);
    const b = this.board();
    if (!b) {
      return;
    }
    this.expanded.set(
      f === 'all'
        ? defaultExpanded(b)
        : new Set(
            this.views()
              .filter((v) => v.visible)
              .map((v) => v.topic.number),
          ),
    );
  }

  protected onFilterKeydown(event: KeyboardEvent, index: number): void {
    const step = { ArrowRight: 1, ArrowDown: 1, ArrowLeft: -1, ArrowUp: -1 }[event.key];
    if (step === undefined) {
      return;
    }
    event.preventDefault();
    const next = (index + step + this.filters.length) % this.filters.length;
    this.selectFilter(this.filters[next]);
    const group = (event.currentTarget as HTMLElement).closest('[role="radiogroup"]');
    group?.querySelectorAll<HTMLElement>('[role="radio"]')[next]?.focus();
  }

  protected isOpen(t: CurriculumTopic): boolean {
    return this.expanded()?.has(t.number) ?? false;
  }

  protected toggle(t: CurriculumTopic): void {
    this.setOpen(t, !this.isOpen(t));
  }

  protected generatingTopic(t: CurriculumTopic): boolean {
    return this.generation()?.topic === t.number;
  }

  protected generatingSlot(s: CurriculumSlot): boolean {
    return this.generation()?.key === s.key;
  }

  protected progressText(g: Generation): string {
    return g.total > 1 ? `Đang sinh ${g.done + 1}/${g.total}…` : 'Đang sinh bài…';
  }

  protected noticeFor(t: CurriculumTopic): Notice | null {
    const n = this.notice();
    return n?.topic === t.number ? n : null;
  }

  protected load(): void {
    this.loadError.set(null);
    const level = this.level();
    this.api.curriculum(level).subscribe({
      next: (b) => {
        if (b.level === this.level()) {
          this.show(b);
        }
      },
      error: (err: unknown) => this.loadError.set(messageOf(err) ?? LOAD_FAILED),
    });
  }

  protected async apply(): Promise<void> {
    this.applyOpen.set(false);
    await this.call(this.applying, () => this.api.applyCurriculum(this.level()), APPLY_FAILED);
  }

  /** The AI writes the topics of a level without a course (one request), kept as its draft. */
  protected async draftWithAI(): Promise<void> {
    await this.call(this.drafting, () => this.api.draftCurriculum(this.level()), DRAFT_FAILED);
  }

  /** Starts a draft from the approved course ("Sửa giáo trình"). */
  protected async edit(): Promise<void> {
    await this.call(this.editing, () => this.api.editCurriculum(this.level()), EDIT_FAILED);
  }

  protected async generateOne(t: CurriculumTopic, slot: CurriculumSlot): Promise<void> {
    if (this.busy()) {
      return;
    }
    this.notice.set(null);
    const ok = await this.generateSlot(t, slot, 0, 1);
    this.generation.set(null);
    if (ok) {
      this.notice.set({ topic: t.number, kind: 'ok', text: `Đã sinh bản nháp “${slot.title}”.` });
    }
  }

  /** Generates the topic's empty slots one after another; stops at the first error. */
  protected async generateEmpty(t: CurriculumTopic): Promise<void> {
    if (this.busy()) {
      return;
    }
    this.notice.set(null);
    this.setOpen(t, true);
    const empty = t.slots.filter((s) => !s.lesson);
    let done = 0;
    for (const slot of empty) {
      if (!(await this.generateSlot(t, slot, done, empty.length))) {
        break;
      }
      done++;
    }
    this.generation.set(null);
    if (done === empty.length) {
      this.notice.set({ topic: t.number, kind: 'ok', text: `Đã sinh ${done} bản nháp.` });
    }
  }

  protected async publish(t: CurriculumTopic, lessonId: string): Promise<void> {
    this.publishing.set(lessonId);
    this.notice.set(null);
    try {
      await firstValueFrom(this.api.setPublished(lessonId, true));
      this.show(await firstValueFrom(this.api.curriculum(this.level())));
      this.notice.set({ topic: t.number, kind: 'ok', text: 'Đã đăng bài.' });
    } catch (err) {
      this.notice.set({ topic: t.number, kind: 'error', text: messageOf(err) ?? PUBLISH_FAILED });
    } finally {
      this.publishing.set(null);
    }
  }

  protected async recheck(
    t: CurriculumTopic,
    slot: CurriculumSlot,
    lessonId: string,
  ): Promise<void> {
    this.rechecking.set(lessonId);
    this.notice.set(null);
    try {
      const checks: LessonChecks = await firstValueFrom(this.api.curriculumChecks(lessonId));
      this.replaceSlot({ ...slot, checks }, slot);
      this.notice.set({ topic: t.number, kind: 'ok', text: `Đã kiểm tra lại “${slot.title}”.` });
    } catch (err) {
      this.notice.set({ topic: t.number, kind: 'error', text: messageOf(err) ?? CHECKS_FAILED });
    } finally {
      this.rechecking.set(null);
    }
  }

  protected askRemove(t: CurriculumTopic, lesson: CurriculumLesson, title: string): void {
    this.opener = document.activeElement instanceof HTMLElement ? document.activeElement : null;
    this.removal.set({ topic: t.number, lesson, title });
  }

  protected askImport(t: CurriculumTopic, slot: CurriculumSlot): void {
    this.opener = document.activeElement instanceof HTMLElement ? document.activeElement : null;
    this.importing.set({ topic: t.number, slot });
  }

  protected cancelImport(): void {
    this.importing.set(null);
    this.opener?.focus();
    this.opener = null;
  }

  /** The imported draft is in its slot: reads the board again and says so. */
  protected async imported(slot: CurriculumSlot): Promise<void> {
    const i = this.importing();
    this.importing.set(null);
    this.opener = null;
    if (!i) {
      return;
    }
    this.notice.set({
      topic: i.topic,
      kind: 'ok',
      text: `Đã nhập bài “${slot.lesson?.title ?? slot.title}” thành nháp.`,
    });
    try {
      this.show(await firstValueFrom(this.api.curriculum(this.level())));
    } catch (err) {
      this.notice.set({ topic: i.topic, kind: 'error', text: messageOf(err) ?? LOAD_FAILED });
    }
    afterNextRender(() => document.getElementById(`topic-toggle-${i.topic}`)?.focus(), {
      injector: this.injector,
    });
  }

  protected cancelRemove(): void {
    this.removal.set(null);
    this.opener?.focus();
    this.opener = null;
  }

  /**
   * Takes the lesson out of the course, deleting it when del (else it stays a draft in the lesson
   * list), reads the board again and says what happened.
   */
  protected async remove(del: boolean): Promise<void> {
    const r = this.removal();
    if (!r) {
      return;
    }
    this.removal.set(null);
    this.opener = null;
    this.removing.set(r.lesson.id);
    this.notice.set(null);
    try {
      await firstValueFrom(this.api.removeCurriculumLesson(r.lesson.id, del));
      this.show(await firstValueFrom(this.api.curriculum(this.level())));
      const text = del
        ? `Đã gỡ và xoá bài “${r.title}”.`
        : `Đã gỡ bài “${r.title}” khỏi giáo trình. Bài vẫn còn ở trang Bài học, dạng nháp.`;
      this.notice.set({ topic: r.topic, kind: 'ok', text });
    } catch (err) {
      this.notice.set({ topic: r.topic, kind: 'error', text: messageOf(err) ?? REMOVE_FAILED });
    } finally {
      this.removing.set(null);
    }
    // The removed line is gone or changed: keep focus on the topic.
    afterNextRender(() => document.getElementById(`topic-toggle-${r.topic}`)?.focus(), {
      injector: this.injector,
    });
  }

  /** A board from the server: the page shows it, opening the topics to look at first. */
  protected show(b: CurriculumBoard): void {
    const statusChanged = this.board()?.status !== b.status;
    this.board.set(b);
    if (this.expanded() === null || statusChanged) {
      this.expanded.set(defaultExpanded(b));
    }
  }

  /** One request that returns the board, with `flag` set while it runs. */
  private async call(
    flag: WritableSignal<boolean>,
    request: () => Observable<CurriculumBoard>,
    fallback: string,
  ): Promise<void> {
    flag.set(true);
    this.pageError.set(null);
    try {
      this.show(await firstValueFrom(request()));
    } catch (err) {
      this.pageError.set(messageOf(err) ?? fallback);
    } finally {
      flag.set(false);
    }
  }

  private setOpen(t: CurriculumTopic, open: boolean): void {
    this.expanded.update((set) => {
      const next = new Set(set ?? []);
      if (open) {
        next.add(t.number);
      } else {
        next.delete(t.number);
      }
      return next;
    });
  }

  /** One POST; on success the slot and the counts of the board are updated. */
  private async generateSlot(
    t: CurriculumTopic,
    slot: CurriculumSlot,
    done: number,
    total: number,
  ): Promise<boolean> {
    this.generation.set({ topic: t.number, key: slot.key, done, total });
    try {
      const filled = await firstValueFrom(this.api.generateSlot(slot.key));
      this.replaceSlot(filled, slot);
      return true;
    } catch (err) {
      const prefix = total > 1 ? `Dừng ở bài “${slot.title}”: ` : '';
      this.notice.set({
        topic: t.number,
        kind: 'error',
        text: prefix + (messageOf(err) ?? GENERATE_FAILED),
      });
      return false;
    }
  }

  private replaceSlot(next: CurriculumSlot, prev: CurriculumSlot): void {
    this.board.update((b) => {
      if (!b) {
        return b;
      }
      const before = lessonState(prev.lesson);
      const after = lessonState(next.lesson);
      const count = (state: RowState) => (after === state ? 1 : 0) - (before === state ? 1 : 0);
      return {
        ...b,
        drafts: b.drafts + count('draft'),
        published: b.published + count('published'),
        topics: b.topics.map((t) => ({
          ...t,
          slots: t.slots.map((s) => (s.key === next.key ? next : s)),
        })),
      };
    });
  }
}

/** The level of ?level=, A1 when absent or unknown. */
function levelOf(value: string | null | undefined): Level {
  return LEVELS.find((l) => l === value) ?? 'A1';
}

function hasDraft(t: CurriculumTopic): boolean {
  return t.slots.some((s) => s.lesson?.draft) || t.others.some((l) => l.draft);
}

/** Topics with a draft to review, plus the first one with an empty slot to generate. */
function defaultExpanded(b: CurriculumBoard): Set<number> {
  const open = new Set(b.topics.filter(hasDraft).map((t) => t.number));
  const next = b.topics.find((t) => t.slots.some((s) => !s.lesson));
  if (next) {
    open.add(next.number);
  }
  return open;
}

/** The server's Vietnamese message, when the error has one. */
function messageOf(err: unknown): string | null {
  if (err instanceof ApiError && err.kind === 'http') {
    const message = (err.body as { message?: unknown } | null)?.message;
    return typeof message === 'string' && message ? message : null;
  }
  return null;
}
